//! Cargo-only embedding of one verified generated contract bundle.
//!
//! The Rust-first generator owns contract production and bundle verification.
//! This module owns only the final projection into `OUT_DIR`: captured schema
//! bytes plus the private descriptor table consumed by the runtime registry.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use pale_contract_codegen::ContractBundle;

/// Render the deterministic private descriptor table for `bundle`.
pub(crate) fn render_descriptors(bundle: &ContractBundle) -> Result<String, String> {
    let mut output = String::new();
    writeln!(
        output,
        "// @generated by pale-contracts/build.rs from the verified Rust-first bundle."
    )
    .expect("String writes are infallible");
    writeln!(
        output,
        "// Do not edit; the checked-in bundle is the sealed projection."
    )
    .expect("String writes are infallible");
    constant(
        &mut output,
        "const SCHEMA_MANIFEST_SHA256: &str",
        bundle.coordinate().schema_manifest_sha256.as_str(),
    )?;
    constant(
        &mut output,
        "const SCHEMA_SET_SHA256: &str",
        bundle.coordinate().schema_set_sha256.as_str(),
    )?;
    constant(
        &mut output,
        "const SCHEMA_MANIFEST_CANONICAL_PREIMAGE: &str",
        bundle.manifest_canonical_preimage(),
    )?;
    writeln!(
        output,
        "static EMBEDDED_SCHEMAS: std::sync::LazyLock<Vec<EmbeddedSchema>> = std::sync::LazyLock::new(|| vec!["
    )
    .expect("String writes are infallible");
    for descriptor in bundle.schema_descriptors() {
        writeln!(output, "    EmbeddedSchema {{").expect("String writes are infallible");
        writeln!(output, "        descriptor: SchemaDescriptor {{")
            .expect("String writes are infallible");
        field(&mut output, "schema_id", descriptor.schema_id(), 12)?;
        field(&mut output, "schema_uri", descriptor.schema_uri(), 12)?;
        option_field(
            &mut output,
            "wire_schema_id",
            descriptor.wire_schema_id(),
            12,
        )?;
        field(
            &mut output,
            "source_path",
            descriptor
                .source_path()
                .to_str()
                .ok_or_else(|| "generated schema path is not UTF-8".to_string())?,
            12,
        )?;
        field(
            &mut output,
            "schema_sha256",
            descriptor.schema_sha256().as_str(),
            12,
        )?;
        field(
            &mut output,
            "raw_schema_sha256_carriage",
            descriptor.raw_schema_sha256_carriage(),
            12,
        )?;
        field(
            &mut output,
            "manifest_entry_canonical",
            descriptor.manifest_entry_canonical(),
            12,
        )?;
        writeln!(output, "        }},").expect("String writes are infallible");
        writeln!(
            output,
            "        source: include_str!(concat!(env!(\"OUT_DIR\"), \"/pale_schema_sources/{}.json\")),",
            descriptor.schema_id()
        )
        .expect("String writes are infallible");
        writeln!(output, "        compiled: std::sync::OnceLock::new(),")
            .expect("String writes are infallible");
        writeln!(
            output,
            "        compiled_definitions: std::sync::OnceLock::new(),"
        )
        .expect("String writes are infallible");
        writeln!(output, "    }},").expect("String writes are infallible");
    }
    writeln!(output, "]);\n").expect("String writes are infallible");
    Ok(output)
}

/// Capture verified contract bytes and editor-only schemas beneath Cargo's output.
pub(crate) fn write_outputs(
    bundle: &ContractBundle,
    authoring_schemas: &std::collections::BTreeMap<String, Vec<u8>>,
    out_dir: &Path,
) -> Result<PathBuf, String> {
    let source_out = out_dir.join("pale_schema_sources");
    fs::create_dir_all(&source_out)
        .map_err(|error| format!("create {}: {error}", source_out.display()))?;
    for descriptor in bundle.schema_descriptors() {
        let path = source_out.join(format!("{}.json", descriptor.schema_id()));
        fs::write(&path, descriptor.bytes())
            .map_err(|error| format!("write {}: {error}", path.display()))?;
    }
    let generated_path = out_dir.join("pale_schema_descriptors.rs");
    fs::write(&generated_path, render_descriptors(bundle)?)
        .map_err(|error| format!("write {}: {error}", generated_path.display()))?;
    let authoring_out = out_dir.join("pale_authoring_schema_sources");
    fs::create_dir_all(&authoring_out)
        .map_err(|error| format!("create {}: {error}", authoring_out.display()))?;
    for (schema_id, bytes) in authoring_schemas {
        let path = authoring_out.join(format!("{schema_id}.json"));
        fs::write(&path, bytes).map_err(|error| format!("write {}: {error}", path.display()))?;
    }
    let authoring_generated_path = out_dir.join("pale_authoring_schemas.rs");
    fs::write(
        &authoring_generated_path,
        render_authoring_schemas(authoring_schemas)?,
    )
    .map_err(|error| format!("write {}: {error}", authoring_generated_path.display()))?;
    Ok(generated_path)
}

/// Render the deterministic editor-only schema lookup table.
fn render_authoring_schemas(
    schemas: &std::collections::BTreeMap<String, Vec<u8>>,
) -> Result<String, String> {
    let mut output = String::new();
    writeln!(
        output,
        "// @generated by pale-contracts/build.rs from Rust-owned authoring schemas."
    )
    .expect("String writes are infallible");
    writeln!(
        output,
        "static AUTHORING_SCHEMAS: [AuthoringSchema; {}] = [",
        schemas.len()
    )
    .expect("String writes are infallible");
    for schema_id in schemas.keys() {
        writeln!(output, "    AuthoringSchema {{").expect("String writes are infallible");
        field(&mut output, "schema_id", schema_id, 8)?;
        writeln!(
            output,
            "        source: include_str!(concat!(env!(\"OUT_DIR\"), \"/pale_authoring_schema_sources/{schema_id}.json\")),"
        )
        .expect("String writes are infallible");
        writeln!(output, "        parsed: OnceLock::new(),").expect("String writes are infallible");
        writeln!(output, "    }},").expect("String writes are infallible");
    }
    writeln!(output, "];\n").expect("String writes are infallible");
    Ok(output)
}

fn literal(value: &str) -> Result<String, String> {
    if value.contains('\0') {
        return Err("generated Rust string contains NUL".into());
    }
    Ok(format!("{value:?}"))
}

fn constant(output: &mut String, declaration: &str, value: &str) -> Result<(), String> {
    writeln!(output, "{declaration} = {};", literal(value)?).expect("String writes are infallible");
    Ok(())
}

fn field(output: &mut String, name: &str, value: &str, indent: usize) -> Result<(), String> {
    writeln!(
        output,
        "{}{}: {},",
        " ".repeat(indent),
        name,
        literal(value)?
    )
    .expect("String writes are infallible");
    Ok(())
}

fn option_field(
    output: &mut String,
    name: &str,
    value: Option<&str>,
    indent: usize,
) -> Result<(), String> {
    let value = match value {
        Some(value) => format!("Some({})", literal(value)?),
        None => "None".to_string(),
    };
    writeln!(output, "{}{}: {value},", " ".repeat(indent), name)
        .expect("String writes are infallible");
    Ok(())
}
